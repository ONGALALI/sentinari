    def pattern_html(p: dict[str, Any]) -> str:
        benefits = (
            f"<div class='benefits'><h3>Potential benefits</h3><p>{e(p['benefits'])}</p></div>"
            if p["benefits"]
            else ""
        )
        evidence = ""
        if p["evidence"]:
            items = "".join(f"<li>{e(t)}</li>" for t in p["evidence"])
            evidence = f"<div class='evidence'><h3>Evidence excerpts</h3><ol>{items}</ol></div>"
        fields_line = ", ".join(e(f) for f in p["fields"])
        return f"""
        <section class="pattern">
          <h2>{e(p['title'])}</h2>
          <p class="meta">Status: <b>{e(p['status'])}</b> &middot; Type: {e(p['pattern_type'])} &middot;
             Confidence: {round(p['confidence'] * 100)}% &middot; Discovered: {e(p['discovered_at'])}</p>
          {f"<p class='meta'>Fields involved: {fields_line}</p>" if fields_line else ""}
          <p class="statement">{e(p['statement'])}</p>
          {benefits}{evidence}
        </section>"""

    sources = ""
    if report["sources"]:
        rows = "".join(
            f"<li>{e(s['name'])} <span class='kind'>({e(s['source_type'])}, {s['files']} document(s))</span>"
            + (f" <a href='{e(s['url'])}'>{e(s['url'])}</a>" if s["url"] else "")
            + "</li>"
            for s in report["sources"]
        )
        sources = f"<section><h2>Data sources involved</h2><ul class='sources'>{rows}</ul></section>"

    works = ""
    if report["works_cited"]:
        items = "".join(f"<li>{e(r)}</li>" for r in report["works_cited"])
