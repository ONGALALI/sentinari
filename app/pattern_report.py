"""Pattern report generation: HTML preview + .pdf download, APA 7th citations.

Reports are rendered from the pattern store + library metadata:
  - Container report: every pattern in a field/combination container, all the
    container's fields, its data sources, and a consolidated Works Cited.
  - Pattern report: one pattern, its evidence, and citations.

The storage-location note (patterns.db tables/columns) is displayed in the UI
only — never inside the HTML or PDF artifacts.
"""
