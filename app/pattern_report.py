def _apa_authors(raw: str) -> str:
    """Best-effort APA author formatting from the stored authors string."""
    raw = str(raw or "").strip()
    if not raw:
        return ""
    parts = [p.strip() for p in re.split(r";|\band\b|,(?![^,]*\b\w{2,}\b)", raw) if p.strip()] or [raw]
    formatted: list[str] = []
    for part in parts[:20]:
        tokens = part.replace(".", " ").split()
        if len(tokens) >= 2:
            surname = tokens[-1]
            initials = " ".join(f"{t[0].upper()}." for t in tokens[:-1] if t)
            formatted.append(f"{surname}, {initials}")
        elif part:
            formatted.append(part)
    if len(formatted) > 1:
        return ", ".join(formatted[:-1]) + ", & " + formatted[-1]
    return formatted[0] if formatted else ""


def _apa_year(raw: str) -> str:
    m = re.search(r"(\d{4})", str(raw or ""))
    return m.group(1) if m else "n.d."


def _apa_reference(doc: dict[str, Any], fallback_title: str = "", fallback_url: str = "") -> str:
    title = str(doc.get("title") or fallback_title or "Untitled source").strip().rstrip(".")
    # Ingested file paths (e.g. data/knowledge_taxonomy/.../makeMovie.py) read
    # better in citations as the bare file name.
    if "/" in title and " " not in title:
        title = title.rstrip("/").rsplit("/", 1)[-1]
    # Machine-style slugs (DOC-1---INPIRARI-DRAFTING-...) read better un-slugified.
    if " " not in title and re.search(r"[-_]{2,}", title):
        words = re.split(r"[-_]+", title)
        title = " ".join(w.capitalize() if w.islower() or w.isupper() else w for w in words)
    authors = _apa_authors(str(doc.get("authors") or ""))
    year = _apa_year(str(doc.get("published_date") or ""))
    source_url = str(doc.get("source_url") or fallback_url or "").strip()
    stype = str(doc.get("source_type") or "").strip().lower()
    publisher = str(doc.get("publisher") or "").strip()

    # Platform naming for non-paper sources.
    if stype == "github" or "github.com" in source_url.lower():
        platform = "GitHub"
        bracket = "[Computer software]"
    elif stype == "huggingface" or "huggingface.co" in source_url.lower():
        platform = "Hugging Face"
        bracket = "[Data set]"
    else:
        platform = ""
        bracket = ""

    byline = f"{authors} " if authors else f"{title}. " if platform else ""
    if platform and authors:
        byline = f"{authors} "
    elif platform:
        # APA style for software/datasets without personal authors: org/owner as author.
        owner = source_url.split("github.com/")[1].split("/")[0] if "github.com/" in source_url.lower() else title.split("/")[0]
        byline = f"{owner.title() if owner else title}. "

    head = f"{byline}({year})."
    title_part = f" {title}" + (f" {bracket}" if bracket else "") + "."
    source_part = f" {publisher}." if publisher and not platform else (f" {platform}." if platform else "")
    url_part = ""
    if source_url:
        if "doi.org/" in source_url.lower():
            url_part = f" {source_url}"
        else:
            url_part = f" {source_url}"
    reference = f"{head}{title_part}{source_part}{url_part}".replace("  ", " ").strip()
    return reference


def _citations_for_pattern(pattern: dict[str, Any]) -> list[str]:
    """APA 7th works-cited entries for a pattern's evidence documents."""
    refs: OrderedDict[str, str] = OrderedDict()
    for item in pattern.get("evidence") or []:
        doc_id = int((item or {}).get("document_id") or 0)
        doc = _library_doc(doc_id) if doc_id else {}
        if not doc:
            doc = {
                "title": str((item or {}).get("document_title") or ""),
                "source_url": str((item or {}).get("source_url") or ""),
                "source_type": "",
                "authors": "",
                "publisher": "",
                "published_date": "",
            }
        if not doc.get("title") and not doc.get("source_url"):
            continue
        ref = _apa_reference(doc, fallback_title=str((item or {}).get("document_title") or ""), fallback_url=str((item or {}).get("source_url") or ""))
        key = ref.lower()
        if ref and key not in refs:
            refs[key] = ref
    return list(refs.values())


